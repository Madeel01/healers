const cron = require("node-cron");
const Invoice = require("../models/invoice");
const User = require("../models/User");
const { sendNotifications } = require("../utils/notificationService");

const START_MONTH = "2026-12"; // first month to bill
const DUE_DAY = 10;
const UNPAID = ["Pending", "Partially Paid", "Overdue"];

const money = (n) => `PKR ${n.toLocaleString("en-US")}`;
const dateText = (d) =>
  new Date(d).toLocaleDateString("en-GB", { day: "numeric", month: "short", timeZone: "UTC" });
const generateInvoiceNumber = async () => {
  const year = new Date().getFullYear();

  const lastInvoice = await Invoice.findOne({
    invoiceNumber: new RegExp(`^INV-${year}-`),
  })
    .sort({ createdAt: -1 })
    .select("invoiceNumber")
    .lean();

  let nextNumber = 1;

  if (lastInvoice?.invoiceNumber) {
    const parts = lastInvoice.invoiceNumber.split("-");
    const current = Number(parts[parts.length - 1]);

    if (!Number.isNaN(current)) {
      nextNumber = current + 1;
    }
  }

  return `INV-${year}-${String(nextNumber).padStart(4, "0")}`;
};

const sendOnce = async (invoice, key, title, message, adminId) => {
  const claimed = await Invoice.updateOne(
    { _id: invoice._id, remindersSent: { $ne: key } },
    { $addToSet: { remindersSent: key } },
  );
  if (claimed.modifiedCount === 0) return; 

  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      await sendNotifications({
        title,
        message,
        type: "Alert",
        audience: "users",
        users: [String(invoice.childId)],
        createdBy: adminId,
        sendPush: true,
      });
      return; 
    } catch (err) {
      console.error(`Send failed (${attempt}/3) for invoice ${invoice._id}:`, err.message);
    }
  }

  await Invoice.updateOne({ _id: invoice._id }, { $pull: { remindersSent: key } });
};

// Step 1: create this month's invoice for every child who doesn't have one yet.
const createInvoices = async (year, month, monthKey, monthName, adminId, onlyChildId = null, testFee = null) => {
    const filter = onlyChildId
                    ? { _id: onlyChildId }                                   // test: just this user
                    : { role: "Child", packageId: { $ne: null } };
  const children = await User.find(filter)
    .select("fullName packageId discountedPrice")
    .populate("packageId", "name title price")
    .lean();

  const billed = (await Invoice.find({ billingMonth: monthKey }).distinct("childId")).map(String);

  for (const child of children) {
    if (billed.includes(String(child._id))) continue;

    const fee = child.discountedPrice ?? child.packageId?.price ?? testFee;
    if (!fee || fee <= 0) continue;

    try {
      await Invoice.create({
        invoiceNumber: await generateInvoiceNumber(),
        childId: child._id,
        createdBy: adminId,
        invoiceDate: new Date(Date.UTC(year, month - 1, 1)),
        dueDate: new Date(Date.UTC(year, month - 1, DUE_DAY)),
        billingMonth: monthKey,
        isAutoGenerated: true,
        items: [{
          serviceName: child.packageId?.name || child.packageId?.title || "Monthly therapy fee",
          description: monthName,
          duration: 1,
          durationUnit: "month",
          quantity: 1,
          rate: fee,
          amount: fee,
        }],
        subTotal: fee,
        totalAmount: fee,
        paidAmount: 0,
        balanceDue: fee,
        status: "Pending",
      });
    } catch (err) {
      console.error(`Invoice failed for child ${child._id}:`, err.message);
    }
  }
};

// Step 2: send "generated" / day 5 / day 9 messages to children who still owe money.
const notifyChildren = async (day, monthKey, adminId, onlyChildId = null) => {
  const query = { status: { $in: UNPAID }, balanceDue: { $gt: 0 } };
  if (onlyChildId) query.childId = onlyChildId;

  const unpaid = await Invoice.find(query).sort({ createdAt: -1 }).lean();

  // group unpaid invoices by child
  const byChild = new Map();
  for (const inv of unpaid) {
    const id = String(inv.childId);
    if (!byChild.has(id)) byChild.set(id, []);
    byChild.get(id).push(inv);
  }

  for (const invoices of byChild.values()) {
    try {
      const current = invoices.find((i) => i.billingMonth === monthKey);
      const olderTotal = invoices
        .filter((i) => i !== current)
        .reduce((sum, i) => sum + i.balanceDue, 0);
      const previous = olderTotal > 0 ? ` Previous pending: ${money(olderTotal)}.` : "";

      // 1) invoice generated
      if (current) {
        await sendOnce(
          current,
          "generated",
          "New Invoice Generated",
          `Your invoice ${current.invoiceNumber} of ${money(current.totalAmount)} is generated. Last date to pay: ${dateText(current.dueDate)}.${previous}`,
          adminId,
        );
      }

      // 2) reminders on the 5th and the 9th
      if (day === 5 || day === 9) {
        const title = day === 9 ? "Fee Due Tomorrow" : "Fee Reminder";
        const lead = day === 9 ? "Last date to pay is tomorrow." : "Reminder: your fee is pending.";

        const message = current
          ? `${lead} Invoice ${current.invoiceNumber}: ${money(current.balanceDue)} remaining.${previous}`
          : `${lead} You have ${money(olderTotal)} pending.`;

        const anchor = current || invoices[0]; // the invoice that remembers we sent it
        await sendOnce(anchor, `${monthKey}-day${day}`, title, message, adminId);
      }
    } catch (err) {
      console.error("Notification failed:", err.message);
    }
  }
};

