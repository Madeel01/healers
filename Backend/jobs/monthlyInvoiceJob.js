const run = async () => {
  try {
    const now = new Date();
    const year = now.getUTCFullYear();
    const month = now.getUTCMonth() + 1;
    const day = now.getUTCDate();
    const monthKey = `${year}-${String(month).padStart(2, "0")}`;
    const monthName = now.toLocaleString("en-GB", { month: "long", year: "numeric", timeZone: "UTC" });

    if (monthKey < START_MONTH) return;

    const admin = await User.findOne({ role: "Admin" }).select("_id").lean();
    if (!admin) return console.error("Monthly invoice job: no Admin user found.");

    await createInvoices(year, month, monthKey, monthName, admin._id);
    await notifyChildren(day, monthKey, admin._id);
  } catch (err) {
    console.error("Monthly invoice job error:", err);
  }
};

exports.start = () => {
  cron.schedule("0 9-20 * * *", run, { timezone: "Asia/Karachi" }); 
  run();
};